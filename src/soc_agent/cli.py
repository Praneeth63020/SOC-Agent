"""Command line entry point.

    python -m soc_agent check                                   # environment, config, Hermes smoke test
    python -m soc_agent validate-alert data/alerts/wazuh_account_compromise.json
    python -m soc_agent plan data/alerts/account_compromise.json              # NVIDIA model
    python -m soc_agent plan data/alerts/account_compromise.json --provider mock [--scenario escape]
    python -m soc_agent plan <alert.json> --json --out plan.json
    python -m soc_agent serve --port 8000                       # FastAPI (POST /alerts/plan)
"""
from __future__ import annotations

import argparse
import json
import sys
import textwrap
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

from soc_agent import __version__
from soc_agent.alerts import AlertError, load_alert
from soc_agent.config import ConfigError, load_settings
from soc_agent.mock_llm import SCENARIOS


def _hermes_version() -> str:
    try:
        return version("hermes-agent")
    except PackageNotFoundError:
        return "NOT INSTALLED"


def _wrap(text: str, indent: str) -> str:
    return textwrap.fill(text, width=100, initial_indent=indent, subsequent_indent=indent + "  ")


def print_plan(res) -> None:
    print(f"\nInvestigation {res.investigation_id}  |  alert {res.alert_id}  |  status: {res.status.upper()}"
          f"  |  {res.duration_ms / 1000:.1f} s")
    p = res.plan
    if not p:
        print(f"\nNo plan. Error: {res.error}")
        return
    gb = p["generated_by"]
    print(f"Generated by: {gb['runtime']} + {gb['provider']} ({gb['model']})"
          f"{'   *** MOCK SCRIPT - NOT AN AI MODEL ***' if gb['mock'] else ''}")
    if p["synthetic_data"]:
        print("Data: SYNTHETIC LAB DATA")
    print("\nSummary:\n" + _wrap(p["summary"], "  "))
    print("\nHypotheses:")
    for h in p["hypotheses"]:
        print(_wrap(f"{h['id']} [{'benign' if h.get('benign') else 'malicious'}] {h['description']}", "  "))
        print(_wrap(f"supported by: {h['would_be_supported_by']}", "       "))
        print(_wrap(f"refuted by:   {h['would_be_refuted_by']}", "       "))
    print("\nKey questions:")
    for q in p["key_questions"]:
        print(_wrap(f"- {q}", "  "))
    print("\nPlanned steps (evidence tools are implemented on Day 2):")
    for s in p["steps"]:
        print(_wrap(f"{s['step']}. [{s['tool']}] {s['objective']}", "  "))
        print(_wrap(f"params:   {json.dumps(s['parameters'], ensure_ascii=False)}", "       "))
        print(_wrap(f"why:      {s['rationale']}", "       "))
        print(_wrap(f"expect:   {s['expected_evidence']}", "       "))
    print("\nSafety notes:")
    for n in p["safety_notes"]:
        print(_wrap(f"- {n}", "  "))
    print("\nData gaps:")
    for g in p["data_gaps"] or ["(none listed)"]:
        print(_wrap(f"- {g}", "  "))


def _check() -> int:
    print(f"soc_agent       {__version__}")
    print(f"hermes-agent    {_hermes_version()}")
    print(f"python          {sys.version.split()[0]}")
    ok = True
    try:
        s = load_settings()
        print(f"provider        {s.llm_provider}\nmodel           {s.model}\nbase_url        {s.base_url or '(in-process mock)'}"
              f"\napi key         {'set (not shown)' if s.llm_provider == 'nvidia' else 'not needed'}"
              f"\nmax_iterations  {s.max_iterations}\nmax_tokens      {s.max_tokens}"
              f"\nhermes_home     {s.hermes_home}\nruns_dir        {s.runs_dir}")
    except ConfigError as e:
        print(f"provider        NOT CONFIGURED: {e}")
        ok = False
    # Smoke test: build the locked-down Hermes agent offline (against the mock) and list its tools.
    try:
        from soc_agent.hermes_runtime import build_agent, exposed_tool_names
        from soc_agent.mock_llm import MockLLMServer
        from soc_agent.tools.planning import DAY1_TOOLS

        with MockLLMServer() as m:
            agent = build_agent(load_settings("mock"), DAY1_TOOLS, session_id="check", base_url=m.base_url)
            tools = exposed_tool_names(agent)
        locked = tools == sorted(t.name for t in DAY1_TOOLS)
        print(f"hermes agent    built OK; tools exposed to the model: {', '.join(tools)}"
              f"{'' if locked else '  <-- UNEXPECTED'}")
        ok = ok and locked
    except Exception as e:
        print(f"hermes agent    FAILED to build: {type(e).__name__}: {e}")
        ok = False
    print("check           " + ("OK" if ok else "PROBLEMS FOUND"))
    return 0 if ok else 1


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="soc_agent", description="Hermes-powered AI SOC analyst (Day 1)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check", help="show versions and configuration; build the locked-down Hermes agent")
    p_val = sub.add_parser("validate-alert", help="normalize + validate an alert file")
    p_val.add_argument("alert")
    p_plan = sub.add_parser("plan", help="ask the Hermes agent for an investigation plan")
    p_plan.add_argument("alert")
    p_plan.add_argument("--provider", choices=["nvidia", "mock"], help="override SOC_LLM_PROVIDER")
    p_plan.add_argument("--scenario", choices=SCENARIOS, help="mock LLM scenario (mock provider only)")
    p_plan.add_argument("--json", action="store_true", help="print the full result as JSON")
    p_plan.add_argument("--out", help="also write the plan JSON to this file")
    p_srv = sub.add_parser("serve", help="run the HTTP API")
    p_srv.add_argument("--host", default="127.0.0.1")
    p_srv.add_argument("--port", type=int, default=8000)
    args = ap.parse_args(argv)

    if args.cmd == "check":
        return _check()

    if args.cmd == "serve":
        import uvicorn
        uvicorn.run("soc_agent.api:app", host=args.host, port=args.port)
        return 0

    try:
        alert = load_alert(args.alert)
    except AlertError as e:
        print(f"Alert rejected: {e}", file=sys.stderr)
        return 2

    if args.cmd == "validate-alert":
        print(json.dumps({k: v for k, v in alert.items() if k != "raw"}, indent=2, ensure_ascii=False))
        print(f"\nOK: {args.alert} is a valid alert ({'raw Wazuh, normalized' if 'raw' in alert else 'normalized'}"
              f"{', SYNTHETIC' if alert['synthetic'] else ''}).", file=sys.stderr)
        return 0

    try:
        settings = load_settings(args.provider)
    except ConfigError as e:
        print(f"Configuration error: {e}", file=sys.stderr)
        return 2
    if args.scenario and not settings.is_mock:
        print("--scenario only applies to --provider mock", file=sys.stderr)
        return 2
    from soc_agent.planner import plan_investigation   # heavy import (Hermes) only when needed

    res = plan_investigation(alert, settings, mock_scenario=args.scenario or "normal")
    if args.json:
        print(json.dumps(res.to_dict(), indent=2, ensure_ascii=False))
    else:
        print_plan(res)
        if res.warnings:
            print("\nWarnings:")
            for w in res.warnings:
                print(_wrap(f"! {w}", "  "))
        print(f"\nRun record (audit): {res.run_record}")
    if args.out and res.plan:
        Path(args.out).write_text(json.dumps(res.plan, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"Plan written to {args.out}", file=sys.stderr)
    return 0 if res.status == "planned" else 1


if __name__ == "__main__":
    sys.exit(main())
