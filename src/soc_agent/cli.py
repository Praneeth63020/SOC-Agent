def _hermes_version() -> str:
    try:
        return version("hermes-agent")
    except PackageNotFoundError:
        return "NOT INSTALLED"


def _wrap(text: str, indent: str) -> str:
    return textwrap.fill(text, width=100, initial_indent=indent, subsequent_indent=indent + "  ")


def _hint(error: str | None, indent: str = "") -> str:
    """The actionable explanation of a known error as an extra line ('' if none)."""
    h = hint_for(error)
    return f"\n{indent}What to do: {h}" if h else ""


def print_plan(res) -> None:
    print(f"\nInvestigation {res.investigation_id}  |  alert {res.alert_id}  |  status: {res.status.upper()}"
          f"  |  {res.duration_ms / 1000:.1f} s")
    p = res.plan
    if not p:
        print(f"\nNo plan. Error: {res.error}{_hint(res.error)}")
        return
    gb = p["generated_by"]
    print(f"Generated by: {gb['runtime']} + {gb['provider']} ({gb['model']})"
          f"{'   *** MOCK SCRIPT - NOT AN AI MODEL ***' if gb['mock'] else ''}")
    if p["synthetic_data"]:
        print("Data: SYNTHETIC LAB DATA")
    print("\nSummary:\n" + _wrap(p["summary"], "  "))
    print("\nHypotheses:")
    for h in p["hypotheses"]:
        print(_wrap(f"{h['id']} [{'benign' if h.get('benign') else 'malicious'}] {h['description']}", "  "))
        print(_wrap(f"supported by: {h['would_be_supported_by']}", "       "))
        print(_wrap(f"refuted by:   {h['would_be_refuted_by']}", "       "))
    print("\nKey questions:")
    for q in p["key_questions"]:
        print(_wrap(f"- {q}", "  "))
    print("\nPlanned steps (run them with: python -m soc_agent investigate <alert.json>):")
    for s in p["steps"]:
        print(_wrap(f"{s['step']}. [{s['tool']}] {s['objective']}", "  "))
        print(_wrap(f"params:   {json.dumps(s['parameters'], ensure_ascii=False)}", "       "))
        print(_wrap(f"why:      {s['rationale']}", "       "))
        print(_wrap(f"expect:   {s['expected_evidence']}", "       "))
    print("\nSafety notes:")
    for n in p["safety_notes"]:
        print(_wrap(f"- {n}", "  "))
    print("\nData gaps:")
    for g in p["data_gaps"] or ["(none listed)"]:
        print(_wrap(f"- {g}", "  "))


def _refs(refs: list[str], show: int = 4) -> str:
    if not refs:
        return "(none)"
    more = f" (+{len(refs) - show} more)" if len(refs) > show else ""
    return ", ".join(refs[:show]) + more


def print_trace(trace: list[dict]) -> None:
    print(f"\nTool-call trace ({len(trace)} call(s)):")
    print(f"  {'#':>2}  {'tool':<20} {'status':<9} {'time':>9}  result")
    for t in trace:
        fault = f"  [FAULT INJECTED: {t['fault_injected']}]" if t.get("fault_injected") else ""
        print(f"  {t['seq']:>2}  {t['tool']:<20} {t['status'].upper():<9} {t['duration_ms']:>7.1f}ms  "
              f"{t.get('summary') or ''}{fault}")
        if t.get("reason"):
            print(_wrap(f"why:  {t['reason']}", "      "))
        shown = json.dumps(t["arguments"], ensure_ascii=False)
        if len(shown) > 240:
            shown = f"{shown[:160]}... ({len(shown)} characters; full arguments in the run record)"
        print(_wrap(f"args: {shown}", "      "))
        if t.get("evidence_refs"):
            print(_wrap(f"refs: {len(t['evidence_refs'])} returned: {_refs(t['evidence_refs'])}", "      "))


def print_evidence_log(log: dict | None) -> None:
    if not log:
        print("\nEvidence log: NONE ACCEPTED")
        return
    print("\nEvidence log (accepted; no severity, verdict or recommendations in this phase):")
    for e in log["executed_steps"]:
        print(_wrap(f"step {e['step']} [{e['tool']}] {e['outcome'].upper()}: {e['reason']}", "  "))
        print(_wrap(f"cited: {_refs(e['evidence_refs'], 6)}", "         "))
    for sk in log["skipped_steps"]:
        print(_wrap(f"step {sk['step']} [{sk['tool']}] SKIPPED: {sk['reason']}", "  "))


def print_investigation(res) -> None:
    print(f"\nInvestigation {res.investigation_id}  |  plan {res.plan_id}  |  status: {res.status.upper()}"
          f"  |  {res.duration_ms / 1000:.1f} s")
    if res.faults:
        print(f"*** FAULT INJECTION ACTIVE (testing only): {res.faults} ***")
    print_trace(res.trace)
    print_evidence_log(res.evidence_log)
    if res.error:
        print(f"\nError: {res.error}")


def _claims(claims: list[dict], indent: str = "     ") -> None:
    for c in claims:
        print(_wrap(f"- {c['statement']}  [{_refs(c['evidence_refs'], 3)}]", indent))


def _event_text(e: dict) -> str:
    who = f"{e['account']} " if e.get("account") else ""
    route = f"{e.get('src_ip') or '?'} -> {e.get('dst_ip') or '?'}"
    return f"{e['event_type']} {who}{route}"


def print_timeline(timeline: list[dict]) -> None:
    from soc_agent.correlate import condense_timeline

    rows = condense_timeline(timeline)
    print(f"\nTimeline ({len(timeline)} events from this run's tool results; repeated events condensed):")
    print(f"  {'time (UTC)':<19} | {'phase':<15} | {'event':<52} | ref")
    for r in rows:
        until = r["last_time"][11:19] if r["last_time"][:10] == r["time"][:10] else r["last_time"][:19].replace("T", " ")
        ev = _event_text(r) + (f" x{r['count']} (until {until})" if r["count"] > 1 else "")
        refs = r["evidence_refs"][0] + (f" .. {r['evidence_refs'][-1].split('#', 1)[1]}" if len(r["evidence_refs"]) > 1
                                        else "")
        print(f"  {r['time'][:19].replace('T', ' '):<19} | {r['phase']:<15} | {ev:<52} | {refs}")


def print_assessment(res) -> None:
    from soc_agent.tools.assessment import QUESTIONS

    a = res.assessment or {}
    pv = a.get("provenance", {})
    print(f"\nAssessment {res.investigation_id}  |  alert {res.alert_id}  |  status: {res.status.upper()}"
          f"  |  {res.duration_ms / 1000:.1f} s")
    print(f"Generated by: {pv.get('runtime')} + {pv.get('provider')} ({pv.get('model')})"
          f"{'   *** MOCK SCRIPT - NOT AN AI MODEL ***' if pv.get('mock') else ''}")
    print(f"Data: {'SYNTHETIC LAB DATA' if pv.get('synthetic_data') else 'NOT MARKED SYNTHETIC'} ({pv.get('data_dir')});"
          f" intel: {pv.get('intel')}")
    if res.faults:
        print(f"*** FAULT INJECTION ACTIVE (testing only): {res.faults} ***")
    f, chk, rub = a.get("findings"), a.get("severity_check"), a.get("rubric", {})
    rs, rc = rub.get("severity", {}), rub.get("confidence", {})
    if f:
        agree = "agrees" if chk["agrees"] else "DIFFERS - see rationale"
        print(f"\nSEVERITY: {f['severity'].upper()}   (rubric: {rs['severity'].upper()}, score {rs['score']}, "
              f"rule {rs['rule'][:3].rstrip(':')} - {agree})")
        print(_wrap(f"rationale: {f['severity_rationale']}", "  "))
        print(_wrap(f"refs: {_refs(f['severity_evidence_refs'], 6)}", "  "))
        print(f"\nCONFIDENCE: {f['confidence'].upper()}   (rubric: {rc['confidence'].upper()}"
              f"{'' if chk['confidence_agrees'] else ' - differs'})")
        print(_wrap(f"rationale: {f['confidence_rationale']}", "  "))
    else:
        print(f"\nNO ACCEPTED FINDINGS. Deterministic rubric for the evidence gathered: severity "
              f"{rs.get('severity', '?').upper()}, confidence {rc.get('confidence', '?').upper()}.")
    for reason in rc.get("reasons", []):
        print(_wrap(f"rubric: {reason}", "  "))
    print_timeline(a.get("timeline", []))
    if f:
        print("\nAnswers (every claim cites evidence returned in this run):")
        for key, q in QUESTIONS.items():
            print(_wrap(q, "  "))
            _claims(f[key])
        print("\nHypotheses:")
        for h in f["hypotheses"]:
            print(_wrap(f"{h['id']} {h['status'].upper()}: {h['reasoning']}  [{_refs(h['evidence_refs'], 3)}]", "  "))
        print("\nMITRE ATT&CK (only where the cited evidence justifies it):")
        for m in f["mitre"] or [{"technique_id": "-", "name": "none justified", "justification": "", "evidence_refs": []}]:
            print(_wrap(f"{m['technique_id']} {m['name']}: {m['justification']}  [{_refs(m['evidence_refs'], 3)}]", "  "))
        print("\nUnknowns:")
        for u in f["unknowns"] or ["(none stated)"]:
            print(_wrap(f"- {u}", "  "))
        if f["alternative_explanations"]:
            print("\nAlternative explanations:")
            for x in f["alternative_explanations"]:
                print(_wrap(f"- {x}", "  "))
        print("\nRecommended next steps (nothing is executed; containment needs analyst approval):")
        for st in f["recommended_next_steps"]:
            tag = "containment, REQUIRES APPROVAL" if st["type"] == "containment" else st["type"]
            print(_wrap(f"- [{tag}] {st['action']}", "  "))
    if a.get("gaps") or a.get("conflicts"):
        print("\nGaps and conflicts (deterministic):")
        for g in a.get("gaps", []):
            print(_wrap(f"gap: {g['statement']}", "  "))
        for c in a.get("conflicts", []):
            print(_wrap(f"conflict: {c['statement']}", "  "))
    print(f"\nRubric agreement: severity {'AGREES' if chk and chk['agrees'] else 'DIFFERS' if chk else 'n/a'}"
          f"{'' if not chk else ' (agent ' + chk['agent_severity'] + ', rubric ' + chk['rubric_severity'] + ')'}; "
          f"confidence {'agrees' if chk and chk['confidence_agrees'] else 'differs' if chk else 'n/a'}")
    print_trace(res.trace)
    if res.error:
        print(f"\nError: {res.error}{_hint(res.error)}")


def _analyze(args, alert) -> int:
    got = _run_settings(args)
    if isinstance(got, int):
        return got
    settings, faults = got
    from soc_agent.assessor import analyze_alert

    plan_res, res = analyze_alert(alert, settings, mock_scenario=args.scenario or "analyze", faults=faults)
    if args.json:
        print(json.dumps({"plan": plan_res.to_dict(), "assessment": res.to_dict() if res else None},
                         indent=2, ensure_ascii=False))
        return 0 if res and res.status == "completed" else 1
    print(f"Plan {plan_res.plan['plan_id'] if plan_res.plan else '-'}: {plan_res.status.upper()} "
          f"({plan_res.duration_ms / 1000:.1f} s; {len(plan_res.plan['steps']) if plan_res.plan else 0} steps, "
          f"{len(plan_res.plan['hypotheses']) if plan_res.plan else 0} hypotheses)"
          f"{'   *** MOCK SCRIPT - NOT AN AI MODEL ***' if settings.is_mock else ''}")
    if res is None:
        print(f"\nNo assessment: planning failed ({plan_res.error}). Run record: {plan_res.run_record}"
              f"{_hint(plan_res.error)}")
        return 1
    print_assessment(res)
    if res.warnings:
        print("\nWarnings:")
        for w in res.warnings:
            print(_wrap(f"! {w}", "  "))
    print(f"\nRun records (audit): {plan_res.run_record}  (planning)\n                     {res.run_record}"
          "  (assessment)")
    return 0 if res.status == "completed" else 1


def _tool(args) -> int:
    from soc_agent.planner import new_investigation_id
    from soc_agent.tools.base import RunContext, call_tool
    from soc_agent.tools.evidence import EVIDENCE_TOOLS
    from soc_agent.tools.planning import GET_ALERT

    specs = {t.name: t for t in [GET_ALERT, *EVIDENCE_TOOLS]}
    if args.name not in specs:
        print(f"Unknown tool {args.name!r}. Tools: {', '.join(sorted(specs))}", file=sys.stderr)
        return 2
    try:
        tool_args = json.loads(args.arguments)
    except json.JSONDecodeError as e:
        print(f"Arguments are not valid JSON: {e}", file=sys.stderr)
        return 2
    if args.timeout is not None and not 0 < args.timeout <= 120:
        print(f"--timeout must be between 0 and 120 seconds, got {args.timeout:g}", file=sys.stderr)
        return 2
    try:
        settings = load_settings("mock")          # no LLM is involved; only limits / data dir are used
        faults = {**settings.faults, **parse_faults(",".join(args.fault or []))}
    except ConfigError as e:
        print(f"Configuration error: {e}", file=sys.stderr)
        return 2
    try:                                          # only get_alert reads the alert
        alert = load_alert(args.alert) if args.name == GET_ALERT.name else {}
    except AlertError as e:
        print(f"Alert rejected: {e}", file=sys.stderr)
        return 2
    ctx = RunContext(investigation_id=new_investigation_id(), alert=alert, data_dir=settings.data_dir,
                     tool_timeout_s=args.timeout if args.timeout is not None else settings.tool_timeout_s,
                     faults=faults)
    result, entry = call_tool(specs[args.name], tool_args, ctx)
    if args.json:
        print(json.dumps(entry, indent=2, ensure_ascii=False, default=str))
    else:
        print(json.dumps(result, indent=2, ensure_ascii=False))
        print(f"\n[{args.name}] status: {entry['status'].upper()}  |  {entry['duration_ms']:.1f} ms  |  "
              f"{entry['result_summary']}")
        if entry["evidence_refs"]:
            print(f"evidence_refs: {_refs(entry['evidence_refs'], 6)}")
        if entry["fault_injected"]:
            print(f"*** FAULT INJECTED: {entry['fault_injected']} (testing only) ***")
    return EXIT_FOR_STATUS.get(entry["status"], 1)


def _trace(args) -> int:
    from soc_agent.api import RUN_ID
    from soc_agent.config import runs_dir
    from soc_agent.investigator import load_trace

    if not RUN_ID.fullmatch(args.investigation_id):
        print("Invalid investigation id (expected INV-YYYYMMDD-XXXXXXXX)", file=sys.stderr)
        return 2
    rec = load_trace(runs_dir(), args.investigation_id)
    if rec is None:                     # a Day 3 run has an assessment record instead
        from soc_agent.assessor import load_assessment
        rec = load_assessment(runs_dir(), args.investigation_id)
    if rec is None:
        print(f"No investigation record for {args.investigation_id} in {runs_dir()}", file=sys.stderr)
        return 1
    if args.json:
        print(json.dumps(rec, indent=2, ensure_ascii=False))
        return 0
    llm = rec.get("llm") or {}
    print(f"Investigation {rec['investigation_id']}  |  plan {rec['plan_id']}  |  status: {str(rec['status']).upper()}"
          f"  |  {llm.get('provider')} ({llm.get('model')}){'  *** MOCK SCRIPT ***' if llm.get('mock') else ''}")
    if rec.get("fault_injection"):
        print(f"*** FAULT INJECTION ACTIVE (testing only): {rec['fault_injection']} ***")
    print_trace(rec.get("trace") or [])
    if rec.get("phase") == "assessment":
        f = (rec.get("assessment") or {}).get("findings")
        print(f"\nAssessment: {'severity ' + f['severity'] + ', confidence ' + f['confidence'] if f else 'NO ACCEPTED FINDINGS'}"
              "  (full record: runs/" + rec["investigation_id"] + ".assessment.json)")
    else:
        print_evidence_log(rec.get("evidence_log"))
    for w in rec.get("warnings") or []:
        print(_wrap(f"! {w}", "  "))
    return 0


def _investigate(args, alert) -> int:
    try:
        settings = load_settings(args.provider)
        faults = parse_faults(",".join(args.fault or []))
    except ConfigError as e:
        print(f"Configuration error: {e}", file=sys.stderr)
        return 2
    if args.scenario and not settings.is_mock:
        print("--scenario only applies to --provider mock", file=sys.stderr)
        return 2
    from soc_agent.investigator import investigate_alert, load_plan, run_investigation

    if args.plan:                      # investigation phase only, from an accepted plan
        try:
            plan = load_plan(args.plan, alert)
        except (OSError, ValueError) as e:
            print(f"Plan rejected: {e}", file=sys.stderr)
            return 2
        from soc_agent.planner import PlanResult
        plan_res = PlanResult(plan["investigation_id"], alert["alert_id"], "planned", plan,
                              run_record=f"(from {args.plan})")
        inv = run_investigation(alert, plan, settings, mock_scenario=args.scenario or "investigate_normal",
                                faults=faults)
    else:
        plan_res, inv = investigate_alert(alert, settings, mock_scenario=args.scenario or "investigate_normal",
                                          faults=faults)
    if args.json:
        print(json.dumps({"plan": plan_res.to_dict(), "investigation": inv.to_dict() if inv else None},
                         indent=2, ensure_ascii=False))
        return 0 if inv and inv.status == "completed" else 1
    print(f"Plan {plan_res.plan['plan_id'] if plan_res.plan else '-'}: {plan_res.status.upper()} "
          f"({plan_res.duration_ms / 1000:.1f} s; {len(plan_res.plan['steps']) if plan_res.plan else 0} steps)"
          f"{'   *** MOCK SCRIPT - NOT AN AI MODEL ***' if settings.is_mock else ''}")
    if plan_res.plan:
        for st in plan_res.plan["steps"]:
            print(_wrap(f"{st['step']}. [{st['tool']}] {st['objective']}", "  "))
    if inv is None:
        print(f"\nNo investigation: planning failed ({plan_res.error}). Run record: {plan_res.run_record}"
              f"{_hint(plan_res.error)}")
        return 1
    print_investigation(inv)
    if inv.warnings:
        print("\nWarnings:")
        for w in inv.warnings:
            print(_wrap(f"! {w}", "  "))
    if args.plan:
        print(f"\nRun record (audit): {inv.run_record}  (investigation; plan from {args.plan})")
    else:
        print(f"\nRun records (audit): {plan_res.run_record}  (planning)\n                     {inv.run_record}"
              "  (investigation)")
    print(f"Trace again: python -m soc_agent trace {inv.investigation_id}")
    return 0 if inv.status == "completed" else 1


def _live_check(s) -> tuple[bool, str]:
    """One tiny chat request (max 4 output tokens) to the configured model: proves key, model and network.
    Only the fixed text "Reply with OK." is sent - no alert or log data."""
    import time

    import httpx

    t0 = time.perf_counter()
    try:
        r = httpx.post(f"{s.base_url}/chat/completions", timeout=30,
                       headers={"Authorization": f"Bearer {s.api_key}"},
                       json={"model": s.model, "max_tokens": 4,
                             "messages": [{"role": "user", "content": "Reply with OK."}]})
    except httpx.HTTPError as e:
        return False, f"FAILED: {type(e).__name__}: {e}{_hint('Connection error', '                ')}"
    ms = (time.perf_counter() - t0) * 1000
    if r.status_code == 200:
        return True, f"OK - {s.model} answered in {ms:.0f} ms (key, model and network work)"
    return False, f"FAILED: HTTP {r.status_code}{_hint(f'HTTP {r.status_code}', '                ')}"


def _check(live: bool = False) -> int:
    """Everything a reviewer needs before a run. Exit 0 = ready (warnings allowed), 1 = a problem to fix."""
    import os
    import platform
    import sqlite3

    from soc_agent.config import analyst_api_token
    from soc_agent.errors import python_problem

    problems, warnings = [], []

    def row(label: str, value: str) -> None:
        print(f"  {label:<16}{value}")

    print("Environment")
    py = python_problem()
    row("python", f"{sys.version.split()[0]}  " + ("OK (3.11-3.13 supported)" if not py else "PROBLEM: " + py))
    if py:
        problems.append("python")
    row("platform", platform.platform(terse=True)
        + ("  (Windows: use WSL2; Hermes does not run natively on Windows)" if os.name == "nt" else ""))
    hv = _hermes_version()
    row("soc_agent", f"{__version__}   hermes-agent {hv}" + ("" if hv == "0.19.0" else "  PROBLEM: 0.19.0 expected"))
    if hv != "0.19.0":
        problems.append("hermes-agent")
    base = load_settings("mock")                 # paths and limits (never needs a key)
    provider = (os.environ.get("SOC_LLM_PROVIDER") or "nvidia").strip().lower()
    key_set = bool(os.environ.get("NVIDIA_API_KEY", "").strip())
    print("LLM")
    row("provider", f"{provider}  (SOC_LLM_PROVIDER; --provider overrides per run)"
        + ("  - MOCK = deterministic script, NOT an AI model" if provider == "mock" else ""))
    row("NVIDIA_API_KEY", "set (value not shown)" if key_set else
        "MISSING - only --provider mock works (scripts/demo.sh then falls back to mock, loudly)")
    nv = None
    try:
        nv = load_settings("nvidia") if key_set else None
    except ConfigError as e:
        problems.append("config")
        row("config", f"PROBLEM: {e}")
    if nv:
        row("model", nv.model)
        row("base_url", nv.base_url)
        if live:
            ok, msg = _live_check(nv)
            row("live request", msg)
            if not ok:
                problems.append("live")
        else:
            row("live request", "not run (python -m soc_agent check --live sends one 4-token request)")
    elif provider == "nvidia":
        warnings.append("NVIDIA_API_KEY missing")
    if provider not in ("nvidia", "mock"):
        problems.append("provider")
        row("provider", f"PROBLEM: unknown provider {provider!r} (nvidia | mock)")
