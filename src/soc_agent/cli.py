def _actions(args) -> int:
    from soc_agent.approvals import ApprovalError, approve, execute, list_actions, reject
    from soc_agent.config import simulated_actions_log

    store = _store()
    if args.action_cmd == "list":
        if args.investigation and not _valid_id(args.investigation):
            return 2
        rows = list_actions(store, args.investigation)
        if args.json:
            print(json.dumps(rows, indent=2, ensure_ascii=False))
        else:
            print("Actions requested by the agent (an analyst decides; execution is SIMULATED):")
            _print_actions(rows, show_investigation=not args.investigation)
        return 0
    try:
        if args.action_cmd == "approve":
            a = approve(store, args.action_id, args.analyst, args.reason)
            print(f"{a['id']} APPROVED by {args.analyst.strip()} ({a['action_type']} {a['target']}). "
                  f"Execute (simulated): python -m soc_agent actions execute {a['id']}")
        elif args.action_cmd == "reject":
            a = reject(store, args.action_id, args.analyst, args.reason)
            print(f"{a['id']} REJECTED by {args.analyst.strip()} ({a['action_type']} {a['target']}).")
        else:
            out = execute(store, args.action_id, simulated_actions_log(), args.analyst)
            a, sim = out["action"], out["simulation"]
            print(f"{a['id']} {'ALREADY EXECUTED (idempotent; nothing repeated)' if out['already_executed'] else 'EXECUTED'}"
                  f" - {sim['simulated_effect']}")
            if not out["already_executed"]:
                print(f"Recorded in the audit trail and {simulated_actions_log()}. Nothing real was changed.")
    except ApprovalError as e:
        print(f"Refused: {e}", file=sys.stderr)
        return 1
    _refresh(store, a["investigation_id"])
    return 0


def _close(args) -> int:
    from soc_agent.approvals import ApprovalError, close

    if not _valid_id(args.investigation_id):
        return 2
